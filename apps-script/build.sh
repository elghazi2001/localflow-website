#!/bin/sh
# Builds one paste-ready file from the source modules.
cd "$(dirname "$0")" || exit 1
{
  echo "// SmartRoutine Studio: all-in-one Apps Script. Generated by build.sh, edit the module files instead."
  for f in Code Mail Sheet; do
    echo; echo "// ===== $f.gs ====="; cat "$f.gs"
  done
} > dist/SmartRoutine.gs
